// --- Computed / helper types not generated by orval ---

export const MANAGEMENT_OPERATIONS = ["cancel", "change_plan", "customer_portal", "pause", "resume"] as const;
export type ManagementOperation = typeof MANAGEMENT_OPERATIONS[number];

export const MANAGEMENT_MODES = ["portal", "api"] as const;
export type ManagementMode = typeof MANAGEMENT_MODES[number];

export enum ManagementAction {
  Redirect = "redirect",
  ShowUI = "show_ui",
  ApiRequired = "api_required",
  CheckoutRequired = "checkout_required",
  Complete = "complete",
  Unsupported = "unsupported",
  Error = "error",
}

export type FragmentType =
  | "link"
  | "html"
  | "script"
  | "script_url"
  | "iframe"
  | "modal"
  | "button"
  | "form";

