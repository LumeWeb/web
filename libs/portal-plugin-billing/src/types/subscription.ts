// --- Type guards ---

export function isManagementOperation(value: string): value is ManagementOperation {
  return (MANAGEMENT_OPERATIONS as readonly string[]).includes(value);
}

export function isManagementAction(value: string): value is ManagementAction {
  return Object.values(ManagementAction).includes(value as ManagementAction);
}

export function isRedirectAction(
  action: ManagementAction,
): action is ManagementAction.Redirect {
  return action === ManagementAction.Redirect;
}

export function isShowUIAction(
  action: ManagementAction,
): action is ManagementAction.ShowUI {
  return action === ManagementAction.ShowUI;
}

export function isApiRequiredAction(
  action: ManagementAction,
): action is ManagementAction.ApiRequired {
  return action === ManagementAction.ApiRequired;
}

export function isUnsupportedAction(
  action: ManagementAction,
): action is ManagementAction.Unsupported {
  return action === ManagementAction.Unsupported;
}

export function isErrorAction(
  action: ManagementAction,
): action is ManagementAction.Error {
  return action === ManagementAction.Error;
}

export function isCheckoutRequiredAction(
  action: ManagementAction,
): action is ManagementAction.CheckoutRequired {
  return action === ManagementAction.CheckoutRequired;
}

