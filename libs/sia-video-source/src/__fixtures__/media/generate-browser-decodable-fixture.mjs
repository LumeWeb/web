#!/usr/bin/env node
/* oxlint-disable typescript/no-unsafe-assignment, typescript/no-unsafe-member-access, typescript/no-unsafe-call, typescript/no-unsafe-argument, typescript/no-unsafe-return */
/**
 * Browser-decodable AVC/AAC fixture generation CONTRACT (ADR 0003 MSE checks).
 *
 * The normalized-MSE browser suite's decode-acceptance tests need a small,
 * deterministic, GENUINELY browser-decodable progressive MP4 (real AVC + AAC
 * sample bytes, complete `mdat`, moov-first, distinct track ids). This script
 * generates and verifies those bytes with a pinned ffmpeg lavfi recipe; the
 * committed fixture (browser-decodable-avc-aac.mp4) is locked by sha256 so the
 * `toolkitMp4Normalization()` browser-decode acceptance only runs when the real
 * bytes are present. The script NEVER fabricates bytes: a candidate that fails
 * the structural contract (2 tracks, distinct ids, vide+soun handlers,
 * non-empty stsz, complete mdat, High@5.0 avc1.640032 + mp4a.40.2, stable
 * sha256) is rejected. (When the ffmpeg recipe was first authored there was no
 * deterministic encoder in repo/CI, so the fixture was ABSENT and the
 * acceptance path stayed OFF; the validator had never run against real
 * encoded bytes. The same latent bug — reading track ids / sample counts with
 * a one-arg u32 that always returned 0 — is what the generated-file
 * validation catches and guards against.)
 *
 * This script is the reproduction + verification contract for that fixture:
 *
 *   node generate-browser-decodable-fixture.mjs             # print the contract
 *   node generate-browser-decodable-fixture.mjs --check     # verify the committed fixture (sha + structure)
 *   node generate-browser-decodable-fixture.mjs --generate # ffmpeg present → produce the real fixture; absent → explain, DO NOT fabricate
 *   node generate-browser-decodable-fixture.mjs --emit-bytes-ts   # re-emit the browser-safe base64 module from committed bytes
 *   node generate-browser-decodable-fixture.mjs --generate --emit-bytes-ts  # generate AND emit the embedded module
 *
 * The ffmpeg recipe is pinned to output AVC High profile @5.0 (level_idc 0x32,
 * codec string avc1.640032) + AAC-LC (mp4a.40.2), matching the documented
 * normalized MIME
 * exactly — a profile/level mismatch between the declared MIME codecs string
 * and the stream's avcC makes strict engines (Chromium) reject the append.
 *
 * It NEVER writes fake bytes: a "generated" fixture that fails the structural
 * contract (2 tracks, distinct ids, vide+soun handlers, non-empty stsz,
 * complete mdat, sha256 stable) is rejected. The sha256 of a successful
 * generation must be carried into:
 *   - `src/__tests__/fixtures/browser-decodable-fixture.ts`
 *     (`HAS_BROWSER_DECODABLE_FIXTURE = true` + `BROWSER_DECODABLE_FIXTURE_SHA256`);
 *   - the `browser-decodable-fixture-contract.spec.ts` manifest.
 * and the `.mp4` bytes committed under this directory so the browser tests can
 * pick them up.
 *
 * Determinism caveat: h.264/AAC encodes depend on the exact ffmpeg/x264 build,
 * so regeneration is only byte-identical on a pinned toolchain. That is why the
 * bytes are committed ONCE and locked by sha256; `--generate` is for
 * reproducing or forgers updating after an intentional re-fixture, not for
 * per-CI regeneration.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const OUT = dirname(fileURLToPath(import.meta.url));
const FIXTURE = join(OUT, 'browser-decodable-avc-aac.mp4');
/**
 * Browser-safe embedded-bytes module (base64) regenerated by --emit-bytes-ts so
 * the node AND browser MSE suites resolve the exact committed bytes without fs
 * or a URL. Kept in src/__tests__/fixtures/ (not under src/__fixtures__/media)
 * because it is a TEST-side consumer of the fixture, like the other fixture
 * builders, and must stay importable from the browser test bundle.
 */
const BYTES_TS = join(OUT, '..', '..', '__tests__', 'fixtures', 'browser-decodable-fixture-bytes.ts');

/** Pinned, reproducible ffmpeg lavfi recipe (no input media, no network). */
const FFMPEG_CMD = [
  'ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
  // 2 s @ 30 fps: still genuinely multi-frame/multi-fragment, while keeping
  // moov+ftyp small enough that the moov-first file classifies inside the
  // DEFAULT 4 KiB head window the worker probes — a moov that overruns 4096
  // bytes aborts sniffContainer before `mdat` and the fixture comes back
  // `container:unknown` through the real pipeline (the exact failure the 3 s
  // variant hit: moov = 4576 B > 4088 budget).
  '-f', 'lavfi', '-i', 'testsrc2=size=320x240:rate=30:duration=2',
  '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=44100:duration=2',
  // High profile @5.0 (yuv420p is valid under High; massively supported in
  // Chromium + Firefox, and a 320x240 stream is far below the declared
  // capability). Pinned so the bytes' real avcC is profile_idc 0x64 (High),
  // compat 0x00, level_idc 0x32 (5.0) — an RFC 6381 codec string of
  // `avc1.640032`, matching the documented normalized output MIME AND the
  // synthetic fixture's real BBB avcC. A declared-MIME vs stream-avcC
  // profile/level mismatch makes strict engines (Chromium) reject the append.
  '-c:v', 'libx264', '-profile:v', 'high', '-level', '5.0', '-pix_fmt', 'yuv420p',
  '-g', '30', '-keyint_min', '30', '-sc_threshold', '0',
  '-x264-params', 'keyint=30:min-keyint=30:scenecut=0',
  '-c:a', 'aac', '-b:a', '96k', '-ac', '2', '-ar', '44100',
  '-fps_mode', 'cfr', '-r', '30',
  '-movflags', '+faststart',
  '-t', '2',
  '-fflags', '+bitexact', '-flags:v', '+bitexact', '-flags:a', '+bitexact',
  FIXTURE,
];

// ---- tiny ISO-BMFF structural checker (self-contained; no deps) --------------

const u32 = (bytes, o) => ((bytes[o] ?? 0) * 2 ** 24) + ((bytes[o + 1] ?? 0) << 16) + ((bytes[o + 2] ?? 0) << 8) + (bytes[o + 3] ?? 0);
const four = (bytes, o) => String.fromCharCode(...bytes.subarray(o, o + 4));

function checkMode() {
  if (!existsSync(FIXTURE)) {
    report('--check browser-decodable-avc-aac.mp4', fail(null, 'fixture ABSENT (a regression: the committed browser-decodable AVC/AAC fixture is missing; regenerate with --generate and restore the pinned sha256)', '<none>'));
    console.log('\nRegenerate with --generate --emit-bytes-ts on a pinned toolchain, then');
    console.log('restore the sha256 in src/__tests__/fixtures/browser-decodable-fixture.ts.');
    return false;
  }
  const bytes = new Uint8Array(readFileSync(FIXTURE));
  return report('--check browser-decodable-avc-aac.mp4', validate(bytes));
}

function children(bytes, start, end) {
  const out = [];
  let off = start;
  while (off + 8 <= end) {
    const size = u32(bytes, off);
    if (size < 8 || off + size > end) return [];
    out.push({ end: off + size, size, start: off, type: four(bytes, off + 4) });
    off += size;
  }
  return off === end ? out : [];
}

/** Writes the browser-safe base64-embedded TS so node AND browser suites share the bytes. */
function emitBytesTs(bytes, sha) {
  const base64 = Buffer.from(bytes).toString('base64');
  const source = `/**
 * GENERATED FILE — do not edit by hand.
 * Regenerate with:
 *   node src/__fixtures__/media/generate-browser-decodable-fixture.mjs --generate --emit-bytes-ts
 * (or re-emit from committed bytes with: ... --emit-bytes-ts).
 *
 * Carries browser-decodable-avc-aac.mp4 (sha256 ${sha}) as base64 so the node
 * AND browser MSE suites resolve the EXACT same bytes with no fs/URL import
 * (this module is browser-safe by construction). The sha below must equal
 * BROWSER_DECODABLE_FIXTURE_SHA256 in browser-decodable-fixture.ts.
 */
const BASE64 = '${base64}';

/** Base64 of the committed browser-decodable-avc-aac.mp4 (see the generator contract). */
export function browserDecodableFixtureBase64(): string {
  return BASE64;
}
`;
  writeFileSync(BYTES_TS, source);
  console.log(`\nEmitted browser-safe embedded bytes module: ${BYTES_TS}`);
  console.log(`  embedded sha256: ${sha}`);
  console.log('Now flip HAS_BROWSER_DECODABLE_FIXTURE=true, pin BROWSER_DECODABLE_FIXTURE_SHA256,');
  console.log('and implement browserDecodableFixtureBytes() from browserDecodableFixtureBase64().');
  return true;
}

/** Re-emits the embedded-bytes TS from the committed candidate (no re-encode). */
function emitBytesTsMode() {
  if (!existsSync(FIXTURE)) {
    console.error('no committed browser-decodable-avc-aac.mp4 to embed; run --generate first.');
    return false;
  }
  const bytes = new Uint8Array(readFileSync(FIXTURE));
  const verdict = validate(bytes);
  if (!report('--emit-bytes-ts', verdict)) {
    console.error('committed bytes violate the fixture contract; refusing to emit.');
    return false;
  }
  return emitBytesTs(bytes, verdict.sha);
}

function fail(_reason, msg, sha) {
  return { audio: false, ok: false, reason: msg, sha, video: false };
}

function generateMode(emitTs) {
  const probe = spawnSync('ffmpeg', ['-version'], { stdio: 'ignore' });
  if (probe.error || probe.status !== 0) {
    console.log('no deterministic ffmpeg on this machine -> cannot generate the real fixture.');
    console.log('This is the documented gap; the acceptance path stays OFF. Nothing was written, no bytes fabricated.');
    printContract();
    return false;
  }
  const run = spawnSync(FFMPEG_CMD[0], FFMPEG_CMD.slice(1), { stdio: 'inherit' });
  if (run.status !== 0 || !existsSync(FIXTURE)) {
    console.error('ffmpeg generation failed; nothing committed.');
    return false;
  }
  const bytes = new Uint8Array(readFileSync(FIXTURE));
  const verdict = validate(bytes);
  if (!report('--generate', verdict)) {
    console.error('generated bytes violate the fixture contract; refusing to keep them.');
    return false;
  }
  console.log(`\nCommitted candidate ready: ${FIXTURE}`);
  console.log(`Publish steps: 1) hash the file as printed above, 2) set`);
  console.log('HAS_BROWSER_DECODABLE_FIXTURE=true and BROWSER_DECODABLE_FIXTURE_SHA256 in');
  console.log('src/__tests__/fixtures/browser-decodable-fixture.ts, 3) update the contract spec manifest.');
  if (emitTs) return emitBytesTs(bytes, verdict.sha);
  return true;
}

// ---- modes -------------------------------------------------------------------

function printContract() {
  console.log(`browser-decodable fixture contract
  file:  ${FIXTURE}
  needs: a SMALL deterministic progressive MP4 (moov-first), one AVC video
         track (avc1, distinct id) + one AAC-LC audio track (mp4a), every
         sample a COMPLETE real frame, no truncated mdat — the bytes the
         normalized-MSE suite feeds a real MediaSource to clear the ADR 0003
         appendability contract.
  generate (ffmpeg present):  ${FFMPEG_CMD.join(' ')}
  state: COMMITTED when valid (see --check); the browser-decode acceptance
         stays OFF until the fixture is present AND its sha256 is pinned in
         src/__tests__/fixtures/browser-decodable-fixture.ts — that pin is
         what flips the decode-acceptance suite on. The tracked demo BBB
         fixtures are video-only + truncated / single-recoverable-sample and
         stay disqualified.
  check (fixture exists):    node ${fileURLToPath(import.meta.url).split('/').pop()} --check
`);
}

function report(label, verdict) {
  console.log(`${label}: ${verdict.ok ? 'OK' : 'CONTRACT VIOLATION'}`);
  if (!verdict.ok) console.log(`  reason: ${verdict.reason}`);
  console.log(`  sha256 ${verdict.sha}`);
  console.log(`  tracks: ${verdict.video ? 'avc1' : '-'} + ${verdict.audio ? 'mp4a' : '-'} (2-track distinct ids required)`);
  return verdict.ok;
}

/** Top-level boxes; returns [] on any malformed size so the check is strict. */
function topLevel(bytes) {
  const out = [];
  let off = 0;
  while (off + 8 <= bytes.length) {
    const size = u32(bytes, off);
    if (size === 1 || size === 0 || size < 8 || off + size > bytes.length) return [];
    out.push({ end: off + size, size, start: off, type: four(bytes, off + 4) });
    off += size;
  }
  return off === bytes.length ? out : [];
}

/** Validates the documented fixture contract; returns { ok, reason, tracks }. */
function validate(bytes) {
  const sha = createHash('sha256').update(bytes).digest('hex');
  const reason = new Set();
  const top = topLevel(bytes);
  if (top.length === 0) return fail(reason, 'top-level box walk is malformed/truncated', sha);
  const moov = top.find((b) => b.type === 'moov');
  const mdat = top.find((b) => b.type === 'mdat');
  if (!moov || !mdat) return fail(reason, 'missing top-level moov/mdat', sha);
  // progressive layout requires moov BEFORE mdat (moov-first)
  if (mdat.start < moov.start) reason.add('moov is NOT first (progressive layout requires ftyp/moov/mdat)');
  const moovKids = children(bytes, moov.start + 8, moov.end);
  const traks = moovKids.filter((b) => b.type === 'trak');
  const ids = [];
  const handlers = [];
  let audio = false;
  let video = false;
  for (const trak of traks) {
    const kids = children(bytes, trak.start + 8, trak.end);
    const tkhd = kids.find((b) => b.type === 'tkhd');
    const mdia = kids.find((b) => b.type === 'mdia');
    if (!tkhd || !mdia) { reason.add('trak missing tkhd/mdia'); continue; }
    const v = bytes[tkhd.start + 8] ?? 0;
    ids.push(u32(bytes, tkhd.start + (v === 1 ? 28 : 20)));
    const mdiaKids = children(bytes, mdia.start + 8, mdia.end);
    const hdlr = mdiaKids.find((b) => b.type === 'hdlr');
    const handler = hdlr ? four(bytes, hdlr.start + 16) : '?';
    handlers.push(handler);
    if (handler === 'soun') audio = true;
    if (handler === 'vide') video = true;
    const minf = mdiaKids.find((b) => b.type === 'minf');
    if (!minf) { reason.add('trak missing minf'); continue; }
    const stbl = children(bytes, minf.start + 8, minf.end).find((b) => b.type === 'stbl');
    if (!stbl) { reason.add('trak missing stbl'); continue; }
    const sb = children(bytes, stbl.start + 8, stbl.end);
    const stsz = sb.find((b) => b.type === 'stsz');
    const stsd = sb.find((b) => b.type === 'stsd');
    if (!stsz || u32(bytes, stsz.start + 16) === 0) reason.add(`${handler} track has zero samples`);
    if (stsd) {
      const entries = children(bytes, stsd.start + 16, stsd.end);
      for (const e of entries) {
        const t = four(bytes, e.start + 4);
        if (t === 'avc1') video = true;
        if (t === 'mp4a') audio = true;
      }
    }
  }
  if (new Set(ids).size !== ids.length) reason.add('duplicate track ids');
  if (ids.length < 2) reason.add('fewer than 2 tracks');
  if (!video || !audio) reason.add('missing AVC video or AAC audio sample entry');
  // complete file: mdat must fit and end where the file ends.
  if (mdat.end !== bytes.length) reason.add('mdat does not end at EOF (truncated file)');
  return { audio, ok: reason.size === 0, reason: [...reason].join('; '), sha, video };
}

const mode = process.argv[2];
const emitTs = process.argv.includes('--emit-bytes-ts');
if (mode === '--check') process.exit(checkMode() ? 0 : 1);
if (mode === '--generate') process.exit(generateMode(emitTs) ? 0 : 1);
if (mode === '--emit-bytes-ts') process.exit(emitBytesTsMode() ? 0 : 1);
printContract();
process.exit(0);
